"""Show how Ryzen AI provider settings change CPU/NPU operator assignment.

The first session omits xlnx_enable_py3_round. The second sets it to 0, as
AMD's Phoenix/Hawk Point installation example does. They use separate cache keys.
The report is generated by AMD's Vitis AI Execution Provider, not inferred
from the provider name.
"""

import argparse
import json
import os
from collections import Counter
from pathlib import Path

import numpy as np
import onnx
import onnxruntime as ort


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MODEL = ROOT / "models" / "amd_multi_model" / "resnet50_pt.onnx"
FIRMWARE = Path(r"C:\Program Files\RyzenAI\1.7.0\voe-4.0-win_amd64\xclbins\phoenix\4x4.xclbin")
REPORT_NAME = "vitisai_ep_report.json"


def make_input(model):
    rng = np.random.default_rng(0)
    inputs = {}
    for item in model.get_inputs():
        if item.type != "tensor(float)":
            raise ValueError(f"This lesson expects float input, got {item.type}")
        shape = tuple(dim if isinstance(dim, int) and dim > 0 else 1 for dim in item.shape)
        inputs[item.name] = rng.random(shape, dtype=np.float32)
    return inputs


def examine(model_path, cache_root, mode):
    key = f"{model_path.stem}_{mode}"
    options = {
        "target": "X1",
        "xclbin": str(FIRMWARE),
        "enable_cache_file_io_in_mem": "0",
        "cache_dir": str(cache_root),
        "cache_key": key,
    }
    if mode == "with_option":
        options["xlnx_enable_py3_round"] = "0"

    session_options = ort.SessionOptions()
    session_options.log_severity_level = 3
    session = ort.InferenceSession(
        str(model_path),
        providers=["VitisAIExecutionProvider"],
        provider_options=[options],
        sess_options=session_options,
    )
    outputs = session.run(None, make_input(session))
    report_path = cache_root / key / REPORT_NAME
    if not report_path.is_file():
        raise FileNotFoundError(f"AMD did not generate an assignment report: {report_path}")
    report = json.loads(report_path.read_text(encoding="utf-8"))
    counts = {row["name"]: row["nodeNum"] for row in report["deviceStat"]}
    cpu_types = Counter(
        row["opType"] for row in report["nodeStat"] if row["device"] != "NPU"
    )
    return {
        "mode": mode,
        "providers": session.get_providers(),
        "assignment": counts,
        "cpu_operator_types": dict(cpu_types),
        "output_shapes": [list(output.shape) for output in outputs],
        "finite_outputs": all(np.isfinite(output).all() for output in outputs),
        "report": str(report_path),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, nargs="?", default=DEFAULT_MODEL)
    parser.add_argument(
        "--cache-dir", type=Path, default=ROOT / "cache" / "operator_assignment"
    )
    args = parser.parse_args()
    model_path = args.model.resolve(strict=True)
    if not FIRMWARE.is_file():
        raise FileNotFoundError(FIRMWARE)

    graph = onnx.load(str(model_path)).graph
    raw_types = Counter(node.op_type for node in graph.node)
    print(f"Model: {model_path.name}")
    print(f"Raw ONNX nodes: {len(graph.node)}; top types: {raw_types.most_common(10)}")
    print("Raw node counts differ from the optimized assignment report.", flush=True)

    cache_root = args.cache_dir.resolve()
    cache_root.mkdir(parents=True, exist_ok=True)
    os.environ["XLNX_ONNX_EP_REPORT_FILE"] = REPORT_NAME
    for mode in ("without_option", "with_option"):
        result = examine(model_path, cache_root, mode)
        print(json.dumps(result, indent=2), flush=True)


if __name__ == "__main__":
    main()
